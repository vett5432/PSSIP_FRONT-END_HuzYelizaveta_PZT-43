function calculateY(x) {
    // 1. Обработка исключительной ситуации: деление на ноль
    if (x === 1) {
        alert("Ошибка: Деление на ноль! x не должен быть равен 1.");
        return null;
    }

    const fraction = (x - 2) / (x - 1);

    // 2. Обработка исключительной ситуации: отрицательный модуль
    // Так как |y| всегда >= 0, выражение справа не может быть меньше нуля
    if (fraction < 0) {
        alert("Ошибка: Модуль числа не может быть отрицательным! Для данного x нет действительных корней y.");
        return null;
    }

    // Возврат результатов расчетов через return оператор
    const y1 = fraction;
    const y2 = -fraction;
    return { y1, y2 };
}